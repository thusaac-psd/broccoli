use sea_orm_migration::prelude::*;

/// Sign-in sessions (`entity::auth_session`): every refresh token belongs to
/// one and every access token names one, so a logout ends one sign-in.
///
/// Rolling-safe: a new table and a nullable column older replicas never read.
/// Refresh tokens issued before it have no session and are refused, so their
/// holders sign in again.
pub struct Migration;

impl MigrationName for Migration {
    fn name(&self) -> &str {
        "m0006_auth_session"
    }
}

const UP: &str = r#"
CREATE TABLE public.auth_session (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT auth_session_pkey PRIMARY KEY (id),
    CONSTRAINT "fk-auth_session-user_id" FOREIGN KEY (user_id) REFERENCES public."user"(id)
);
CREATE INDEX "idx-auth_session-user_id" ON public.auth_session USING btree (user_id);

ALTER TABLE public.refresh_tokens ADD COLUMN session_id bigint;
ALTER TABLE public.refresh_tokens
    ADD CONSTRAINT "fk-refresh_tokens-session_id" FOREIGN KEY (session_id)
    REFERENCES public.auth_session(id) ON DELETE CASCADE;
CREATE INDEX "idx-refresh_tokens-session_id" ON public.refresh_tokens USING btree (session_id);
"#;

const DOWN: &str = r#"
ALTER TABLE public.refresh_tokens DROP COLUMN session_id;
DROP TABLE public.auth_session;
"#;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager.get_connection().execute_unprepared(UP).await?;
        Ok(())
    }

    async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager.get_connection().execute_unprepared(DOWN).await?;
        Ok(())
    }
}
