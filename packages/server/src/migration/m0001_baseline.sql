-- The schema the m0001 baseline creates. Frozen: a schema change is a new
-- migration, never an edit here (see `crate::migration`).

CREATE FUNCTION public.broccoli_notify_claim() RETURNS trigger
    LANGUAGE plpgsql
    AS $$ BEGIN IF NEW.status IN ('Queued') AND (TG_OP = 'INSERT' OR OLD.status NOT IN ('Queued')) THEN PERFORM pg_notify('broccoli_claim', 'queued'); END IF; IF TG_OP = 'UPDATE' AND OLD.owner_server_id IS NOT NULL AND OLD.status IN ('Pending', 'Compiling', 'Running') AND NEW.status NOT IN ('Pending', 'Compiling', 'Running') THEN PERFORM pg_notify('broccoli_claim', 'freed:' || OLD.owner_server_id); END IF; RETURN NULL; END $$;

CREATE FUNCTION public.broccoli_plugin_config_changed() RETURNS trigger
    LANGUAGE plpgsql
    AS $$ BEGIN PERFORM nextval('plugin_config_epoch'); PERFORM pg_notify('broccoli_claim', 'config'); RETURN NULL; END $$;

