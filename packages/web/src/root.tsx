import '@/App.css';

import { LOCALE_STORAGE_KEY } from '@broccoli/web-sdk/i18n';
import { THEME_STORAGE_KEY } from '@broccoli/web-sdk/theme';
import {
  isChunkLoadError,
  isStylesheetPreloadError,
} from '@broccoli/web-sdk/utils';
import { useEffect, useMemo } from 'react';
import {
  isRouteErrorResponse,
  Links,
  Meta,
  Outlet,
  Scripts,
  ScrollRestoration,
  useRouteError,
} from 'react-router';
import sharedDepsMap from 'virtual:shared-deps-map';

import { AppErrorPage } from '@/components/AppErrorPage';
import { BaseProviders } from '@/components/BaseProviders';
import { ErrorReporter } from '@/components/error-reporter';
import { getSubmissionScrollKey } from '@/features/submission/utils/navigation';
import {
  canReloadForFreshChunks,
  reloadForFreshChunks,
} from '@/lib/chunk-reload';
import { reportError, reportVitals } from '@/lib/telemetry';

export function Layout({ children }: { children: React.ReactNode }) {
  useEffect(() => {
    document.documentElement.style.opacity = '';
  }, []);

  useEffect(() => {
    reportVitals();
  }, []);

  useEffect(() => {
    const onUnhandledRejection = (event: PromiseRejectionEvent) => {
      reportError({
        message: event.reason?.message ?? String(event.reason),
        stack: event.reason?.stack,
      });
    };
    window.addEventListener('unhandledrejection', onUnhandledRejection);

    const onError = (event: ErrorEvent) => {
      reportError({
        message: event.message,
        stack: event.error?.stack,
        url: event.filename
          ? `${event.filename}:${event.lineno}:${event.colno}`
          : undefined,
      });
    };
    window.addEventListener('error', onError);

    // A chunk's stylesheet failed to preload. Vite never asks for it again,
    // so the code would load unstyled: reload for fresh chunks instead. If
    // that was just tried, or the browser is offline, the import fails into
    // its caller. Every other preload failure is left to the importer's own
    // retry.
    const onPreloadError = (event: Event) => {
      const { payload } = event as Event & { payload?: unknown };
      if (isStylesheetPreloadError(payload) && reloadForFreshChunks()) {
        event.preventDefault();
      }
    };
    window.addEventListener('vite:preloadError', onPreloadError);

    return () => {
      window.removeEventListener('unhandledrejection', onUnhandledRejection);
      window.removeEventListener('error', onError);
      window.removeEventListener('vite:preloadError', onPreloadError);
    };
  }, []);

  return (
    // The boot script below and then `I18nProvider` set `lang` to the UI
    // locale; React never rewrites this constant, so they keep it.
    <html lang="en" suppressHydrationWarning>
      <head>
        <meta charSet="UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        {/* Import map for dynamically loaded plugins. Must precede all module scripts.
            Maps bare specifiers (react, etc.) to the host app's module URLs so
            plugins loaded from the backend share the same instances.
            Generated by the shared-deps Vite plugin (virtual:shared-deps-map).
            Content is a build-time constant with no user input — safe from XSS. */}
        {Object.keys(sharedDepsMap).length > 0 && (
          <script
            type="importmap"
            dangerouslySetInnerHTML={{
              __html: JSON.stringify({ imports: sharedDepsMap }),
            }}
          />
        )}
        <Meta />
        <Links />
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){var t=localStorage.getItem('${THEME_STORAGE_KEY}');if(!t)t=matchMedia('(prefers-color-scheme:dark)').matches?'dark':'light';document.documentElement.classList.add(t);var l=localStorage.getItem('${LOCALE_STORAGE_KEY}');if(l&&l!=='undefined'){document.documentElement.lang=l;if(l!=='en')document.documentElement.style.opacity='0'}})()`,
          }}
        />
      </head>
      <body>
        {children}
        <ScrollRestoration getKey={getSubmissionScrollKey} />
        <Scripts />
      </body>
    </html>
  );
}

export default function Root() {
  return <Outlet />;
}

/**
 * Every error no route handles lands here: a render crash, or code that
 * failed to load (offline for a moment, or a redeploy removed the chunks this
 * page points at). A lazy import's own caller retries first (see `retryLoad`
 * in the SDK), and React Router reloads the page itself when a route module
 * fails to load; code that still fails reloads once here for fresh chunks
 * (once back online, if the browser is offline). Anything else gets a
 * translated error page.
 */
export function ErrorBoundary() {
  const error = useRouteError();
  const chunkLoad = isChunkLoadError(error);
  const reloading = useMemo(
    () => chunkLoad && canReloadForFreshChunks(),
    [chunkLoad],
  );

  useEffect(() => {
    if (reloading) {
      reloadForFreshChunks();
      return;
    }
    reportError(
      isRouteErrorResponse(error)
        ? { message: `${error.status} ${error.statusText}` }
        : error instanceof Error
          ? { message: error.message, stack: error.stack }
          : { message: String(error) },
    );
  }, [error, reloading]);

  // Offline, no reload was attempted (it would land on the browser's offline
  // page); try once the connection is back.
  useEffect(() => {
    if (!chunkLoad || reloading) return;
    const onOnline = () => reloadForFreshChunks();
    window.addEventListener('online', onOnline);
    return () => window.removeEventListener('online', onOnline);
  }, [chunkLoad, reloading]);

  // The translated page needs the providers the crash may have come from;
  // should they fail again, ErrorReporter falls back to plain English.
  return (
    <ErrorReporter>
      <BaseProviders>
        <AppErrorPage chunkLoad={chunkLoad} reloading={reloading} />
      </BaseProviders>
    </ErrorReporter>
  );
}
